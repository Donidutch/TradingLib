"""Research memory: what the workspace already knows about one symbol.

The Stock Research page's *Research memory* panel has three narrative rows -
current thesis, open questions, sources. The source counts were always real, but
the two narrative rows need something to write them. This module is that
generator.

It is deliberately *not* an LLM summariser. It composes the recorded research
objects that already exist - hypotheses (with their status, falsifier and
evidence), agent findings, and knowledge entries - into two statements, and it
says which objects each statement came from. Nothing is invented: a symbol with
no recorded research produces an explicit "nothing recorded" thesis and an empty
question list, never a plausible-sounding paragraph.

The ranking rules, stated once:

* **Current thesis** - the strongest *standing* claim. Hypotheses outrank
  findings because a hypothesis carries a falsifier. Among hypotheses, a later
  lifecycle stage wins (validated > testing > active > draft), ties broken by
  evidence count and then recency. When no hypothesis names the symbol, the
  highest-confidence non-dismissed finding stands in, labelled as a finding.
* **Open questions** - everything still unsettled: hypotheses that are not yet
  validated (each phrased through its own falsifier, which is literally the
  open question), plus findings that are new or under review, plus any
  hypothesis whose evidence links contradict it.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, Final

from tradinglib.agents.findings import Finding, FindingsStore, FindingStatus, get_findings_store
from tradinglib.agents.knowledge import KnowledgeBase, get_knowledge_base
from tradinglib.research.hypotheses import (
    Hypothesis,
    HypothesisRegistry,
    HypothesisStatus,
    get_hypothesis_registry,
)

logger = logging.getLogger(__name__)

#: Lifecycle rank used to pick the standing thesis. Higher wins.
STATUS_RANK: Final[dict[HypothesisStatus, int]] = {
    HypothesisStatus.VALIDATED: 5,
    HypothesisStatus.TESTING: 4,
    HypothesisStatus.ACTIVE: 3,
    HypothesisStatus.DRAFT: 2,
    HypothesisStatus.ARCHIVED: 1,
    HypothesisStatus.REJECTED: 0,
}

#: Hypothesis states that are still open questions rather than settled answers.
OPEN_STATUSES: Final[frozenset[HypothesisStatus]] = frozenset(
    {HypothesisStatus.DRAFT, HypothesisStatus.ACTIVE, HypothesisStatus.TESTING}
)

#: Finding states that are still open questions.
OPEN_FINDING_STATUSES: Final[frozenset[FindingStatus]] = frozenset(
    {FindingStatus.NEW, FindingStatus.TRIAGED}
)

#: How many open questions the panel shows before it starts counting the rest.
MAX_QUESTIONS: Final[int] = 6


@dataclass(slots=True)
class MemoryStatement:
    """One narrative row plus the objects it was composed from."""

    text: str
    kind: str
    refs: list[dict[str, Any]] = field(default_factory=list)
    detail: str | None = None

    def as_dict(self) -> dict[str, Any]:
        """Return a JSON-serialisable mapping for the API layer."""
        return {
            "text": self.text,
            "kind": self.kind,
            "detail": self.detail,
            "refs": list(self.refs),
        }


@dataclass(slots=True)
class ResearchMemory:
    """The composed memory for one symbol."""

    symbol: str
    thesis: MemoryStatement
    questions: list[MemoryStatement] = field(default_factory=list)
    counts: dict[str, int] = field(default_factory=dict)
    generated_at: datetime | None = None

    def as_dict(self) -> dict[str, Any]:
        """Return a JSON-serialisable mapping for the API layer."""
        return {
            "symbol": self.symbol,
            "thesis": self.thesis.as_dict(),
            "questions": [item.as_dict() for item in self.questions],
            "question_count": len(self.questions),
            "counts": dict(self.counts),
            "generated_at": self.generated_at.isoformat() if self.generated_at else None,
            "basis": (
                "composed from recorded hypotheses, agent findings and knowledge entries that "
                "name this symbol; no text is generated by a model"
            ),
        }


def _mentions(text: str | None, symbol: str) -> bool:
    """Return whether ``text`` names ``symbol`` as a standalone token."""
    if not text:
        return False
    upper = text.upper()
    index = upper.find(symbol)
    while index != -1:
        before = upper[index - 1] if index else " "
        after = upper[index + len(symbol)] if index + len(symbol) < len(upper) else " "
        if not before.isalnum() and not after.isalnum():
            return True
        index = upper.find(symbol, index + 1)
    return False


def hypotheses_for(registry: HypothesisRegistry, symbol: str) -> list[Hypothesis]:
    """Return hypotheses that name ``symbol`` in their text or tags."""
    out: list[Hypothesis] = []
    for item in registry.list(include_evidence=True):
        if symbol in {tag.upper() for tag in item.tags}:
            out.append(item)
            continue
        if any(_mentions(text, symbol) for text in (item.title, item.statement, item.rationale)):
            out.append(item)
    return out


def _thesis_sort_key(item: Hypothesis) -> tuple[int, int, float]:
    """Sort key that puts the strongest standing hypothesis first."""
    stamp = item.updated_at or item.created_at
    return (
        STATUS_RANK.get(item.status, 0),
        len([link for link in item.evidence if link.supports]),
        stamp.timestamp() if stamp else 0.0,
    )


def _hypothesis_ref(item: Hypothesis) -> dict[str, Any]:
    """Reference mapping the UI links a narrative row back to."""
    return {
        "kind": "hypothesis",
        "id": item.id,
        "title": item.title,
        "status": str(item.status),
        "evidence": len(item.evidence),
    }


def _finding_ref(item: Finding) -> dict[str, Any]:
    """Reference mapping for a finding used in a narrative row."""
    return {
        "kind": "finding",
        "id": item.id,
        "title": item.title,
        "status": str(item.status),
        "confidence": item.confidence_pct,
        "agent": item.agent_id,
    }


class ResearchMemoryComposer:
    """Composes the *Research memory* narrative rows for a symbol.

    Args:
        hypotheses: the Strategy Lab hypothesis registry.
        findings: the agent findings store.
        knowledge: the knowledge base (used for the source count only).
    """

    def __init__(
        self,
        *,
        hypotheses: HypothesisRegistry | None = None,
        findings: FindingsStore | None = None,
        knowledge: KnowledgeBase | None = None,
    ) -> None:
        self._hypotheses = hypotheses
        self._findings = findings
        self._knowledge = knowledge

    @property
    def hypotheses(self) -> HypothesisRegistry:
        """The hypothesis registry this composer reads."""
        if self._hypotheses is None:
            self._hypotheses = get_hypothesis_registry()
        return self._hypotheses

    @property
    def findings(self) -> FindingsStore:
        """The findings store this composer reads."""
        if self._findings is None:
            self._findings = get_findings_store()
        return self._findings

    @property
    def knowledge(self) -> KnowledgeBase:
        """The knowledge base this composer reads."""
        if self._knowledge is None:
            self._knowledge = get_knowledge_base()
        return self._knowledge

    def compose(self, symbol: str) -> ResearchMemory:
        """Compose the memory for ``symbol`` (upper-case ticker)."""
        sym = symbol.strip().upper()
        hypotheses = hypotheses_for(self.hypotheses, sym)
        findings = self.findings.list(symbol=sym, limit=0)
        try:
            knowledge_hits = self.knowledge.search(sym, limit=25)
        except Exception:  # noqa: BLE001 - a missing FTS index must not break the panel
            logger.debug("knowledge search for %s failed", sym, exc_info=True)
            knowledge_hits = []
        memory = ResearchMemory(
            symbol=sym,
            thesis=self._thesis(sym, hypotheses, findings),
            questions=self._questions(sym, hypotheses, findings),
            counts={
                "hypotheses": len(hypotheses),
                "findings": len(findings),
                "knowledge": len(knowledge_hits),
                "evidence": sum(len(item.evidence) for item in hypotheses),
            },
            generated_at=_now(),
        )
        return memory

    # --- narrative rows ---------------------------------------------------
    def _thesis(
        self, symbol: str, hypotheses: list[Hypothesis], findings: list[Finding]
    ) -> MemoryStatement:
        """Return the standing thesis row."""
        standing = [item for item in hypotheses if item.status != HypothesisStatus.REJECTED]
        if standing:
            lead = max(standing, key=_thesis_sort_key)
            supporting = len([link for link in lead.evidence if link.supports])
            against = len(lead.evidence) - supporting
            detail = (
                f"{lead.id} is {lead.status} with {supporting} supporting and {against} "
                f"contradicting evidence link(s); falsifier: {lead.falsifier}"
            )
            return MemoryStatement(
                text=lead.statement or lead.title,
                kind="hypothesis",
                detail=detail,
                refs=[_hypothesis_ref(lead)],
            )
        live = [item for item in findings if item.status != FindingStatus.DISMISSED]
        if live:
            lead_finding = max(
                live,
                key=lambda item: (
                    item.confidence_pct or 0.0,
                    item.created_at.timestamp() if item.created_at else 0.0,
                ),
            )
            return MemoryStatement(
                text=lead_finding.summary or lead_finding.title,
                kind="finding",
                detail=(
                    f"no hypothesis names {symbol}; the standing claim is agent finding "
                    f"{lead_finding.id} ({lead_finding.status}), which carries no falsifier"
                ),
                refs=[_finding_ref(lead_finding)],
            )
        rejected = [item for item in hypotheses if item.status == HypothesisStatus.REJECTED]
        if rejected:
            return MemoryStatement(
                text=(
                    f"No standing thesis: every hypothesis naming {symbol} "
                    f"({len(rejected)}) has been rejected."
                ),
                kind="empty",
                detail="a rejected hypothesis is recorded history, not a claim",
                refs=[_hypothesis_ref(item) for item in rejected[:4]],
            )
        return MemoryStatement(
            text=(
                f"Nothing recorded for {symbol}. A thesis appears here once a Strategy Lab "
                "hypothesis or an agent finding names this symbol; TradingLib does not write one."
            ),
            kind="empty",
            detail="no hypothesis, finding or knowledge entry names this symbol",
        )

    def _questions(
        self, symbol: str, hypotheses: list[Hypothesis], findings: list[Finding]
    ) -> list[MemoryStatement]:
        """Return the open-question rows, most consequential first."""
        out: list[MemoryStatement] = []
        for item in sorted(hypotheses, key=_thesis_sort_key, reverse=True):
            if item.status not in OPEN_STATUSES:
                continue
            question = item.falsifier.strip() or f"What would disprove {item.title}?"
            out.append(
                MemoryStatement(
                    text=question,
                    kind="falsifier",
                    detail=f"{item.id} is {item.status} - the falsifier is still unanswered",
                    refs=[_hypothesis_ref(item)],
                )
            )
        for item in hypotheses:
            contradicting = [link for link in item.evidence if not link.supports]
            if not contradicting:
                continue
            out.append(
                MemoryStatement(
                    text=(
                        f"{item.title}: {len(contradicting)} evidence link(s) contradict the "
                        "statement and have not been reconciled."
                    ),
                    kind="contradiction",
                    detail=", ".join(
                        f"{link.kind}:{link.ref}" for link in contradicting[:4]
                    ),
                    refs=[_hypothesis_ref(item)],
                )
            )
        for item in findings:
            if item.status not in OPEN_FINDING_STATUSES:
                continue
            out.append(
                MemoryStatement(
                    text=f"{item.title} — recorded by an agent and not yet dispositioned.",
                    kind="finding",
                    detail=(
                        f"{item.id} is {item.status}"
                        + (
                            f" at {item.confidence_pct:.0f}% confidence"
                            if item.confidence_pct is not None
                            else ""
                        )
                    ),
                    refs=[_finding_ref(item)],
                )
            )
        return out[:MAX_QUESTIONS]


def _now() -> datetime:
    """Return the current UTC instant (indirection keeps tests deterministic)."""
    from tradinglib.data.base import utcnow

    return utcnow()


_composer: ResearchMemoryComposer | None = None


def get_memory_composer() -> ResearchMemoryComposer:
    """Return the process-wide research-memory composer."""
    global _composer
    if _composer is None:
        _composer = ResearchMemoryComposer()
    return _composer


def reset_memory_composer(
    composer: ResearchMemoryComposer | None = None,
) -> ResearchMemoryComposer:
    """Replace the process-wide composer (used by the app factory and tests)."""
    global _composer
    _composer = composer or ResearchMemoryComposer()
    return _composer
